import os
import re
import sqlite3
from datetime import datetime, timedelta, timezone
from pathlib import Path
from urllib.parse import parse_qs, urlparse

import pytest
from playwright.sync_api import sync_playwright, expect

from tests.test_browser import live


@pytest.mark.skipif(os.getenv('SKIP_BROWSER') == '1', reason='Chromium não instalado')
def test_recipes_suggestions_checkout_consent_and_campaign_preview(live, tmp_path):
    artifacts = Path('artifacts')
    artifacts.mkdir(exist_ok=True)
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=os.getenv('PLAYWRIGHT_CHROMIUM_EXECUTABLE') or None)
        context = browser.new_context(viewport={'width': 1440, 'height': 1000})
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(live + '/entrar')
        page.get_by_label('E-mail', exact=True).fill('demo@example.com')
        page.get_by_label('Senha', exact=True).fill('senha-de-teste-segura')
        page.get_by_role('button', name='Entrar no painel').click()
        page.wait_for_url('**/painel')
        page.get_by_role('button', name='Insumos e fichas', exact=True).click()
        page.get_by_role('button', name='Novo insumo', exact=True).click()
        page.get_by_label('Nome do insumo', exact=True).fill('Carne bovina')
        page.get_by_label('Saldo inicial', exact=True).fill('1.000')
        page.get_by_label('Alerta de estoque baixo', exact=True).fill('0.200')
        page.get_by_label('Custo de 1 kg, 1 l ou 1 un (R$)', exact=True).fill('30.00')
        page.get_by_role('button', name='Salvar insumo', exact=True).click()
        expect(page.locator('#modal')).not_to_be_visible()
        page.locator('tr').filter(has=page.get_by_text('Burger da casa', exact=True)).get_by_role('button', name='Montar ficha', exact=True).click()
        page.get_by_role('button', name='Adicionar ingrediente', exact=True).click()
        page.locator('[data-recipe-line] input').fill('0.150')
        expect(page.locator('#recipe-cost')).to_contain_text('4,50')
        page.get_by_role('button', name='Salvar ficha técnica', exact=True).click()
        expect(page.locator('#modal')).not_to_be_visible()
        expect(page.locator('tr').filter(has=page.get_by_text('Burger da casa', exact=True))).to_contain_text('4,50')
        page.screenshot(path=str(artifacts / 'insumos-desktop.png'), full_page=True)
        page.get_by_role('button', name='Marketing', exact=True).click()
        page.get_by_label('Suco natural', exact=True).check()
        page.get_by_role('button', name='Salvar sugestões', exact=True).click()
        expect(page.locator('#toast')).to_contain_text('Sugestões da sacola atualizadas')
        mobile = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
        customer = mobile.new_page()
        customer.on('pageerror', lambda error: errors.append(str(error)))
        customer.goto(live + '/loja/bistro-da-vila')
        customer.get_by_role('button', name='Ver Burger da casa', exact=True).click()
        customer.get_by_role('button', name='Adicionar •').click()
        customer.get_by_role('button', name='Ver minha sacola').click()
        expect(customer.locator('.basket-suggestions')).to_contain_text('Suco natural')
        customer.screenshot(path=str(artifacts / 'sacola-sugestoes-mobile.png'), full_page=True)
        customer.locator('.basket-suggestion').get_by_role('button', name='Adicionar', exact=True).click()
        expect(customer.locator('.cart-line')).to_have_count(2)
        customer.get_by_role('button', name='Continuar pedido').click()
        customer.get_by_label('Seu nome', exact=True).fill('Cliente Recompra')
        customer.get_by_label('WhatsApp com DDD').fill('11999999999')
        customer.get_by_label('Endereço completo').fill('Rua dos Testes, 123, Centro')
        customer.get_by_label('Quero receber ofertas desta loja pelo WhatsApp.', exact=False).check()
        customer.get_by_role('button', name='Confirmar pedido').click()
        customer.wait_for_url('**/pedido/**')
        tracking = customer.url
        page.get_by_role('button', name='Pedidos', exact=True).click()
        card = page.locator('.order-card').filter(has_text='Cliente Recompra')
        card.get_by_role('button', name='Aceitar pedido', exact=True).click()
        card.get_by_role('button', name='Marcar pronto', exact=True).click()
        card.get_by_role('button', name='Saiu para entrega', exact=True).click()
        card.get_by_role('button', name='Concluir entrega', exact=True).click()
        page.get_by_role('button', name='Insumos e fichas', exact=True).click()
        expect(page.locator('tr').filter(has=page.get_by_text('Carne bovina', exact=True)).first).to_contain_text('0,85 kg')
        page.get_by_role('button', name='Marketing', exact=True).click()
        expect(page.locator('#audience-list')).to_contain_text('Cliente Recompra')
        expect(page.locator('#audience-list')).to_contain_text('Autorizadas')
        page.screenshot(path=str(artifacts / 'marketing-desktop.png'), full_page=True)
        page.get_by_role('button', name='Nova campanha', exact=True).click()
        page.get_by_label('Nome da campanha', exact=True).fill('Sexta do burger')
        page.get_by_role('button', name='Ver prévia e público', exact=True).click()
        expect(page.locator('#campaign-preview')).to_contain_text('1 cliente com autorização')
        expect(page.locator('#campaign-preview .message-preview')).to_contain_text('Olá, Cliente!')
        expect(page.locator('#campaign-preview a')).to_have_attribute('href', re.compile(r'^https://wa.me/5511999999999\?text='))
        page.get_by_role('button', name='Salvar rascunho', exact=True).click()
        expect(page.locator('.campaign-list')).to_contain_text('Sexta do burger')
        customer.goto(live + '/loja/bistro-da-vila')
        customer.get_by_role('button', name='Ver Burger da casa', exact=True).click()
        customer.get_by_role('button', name='Adicionar •').click()
        customer.get_by_role('button', name='Ver minha sacola').click()
        customer.get_by_role('button', name='Continuar pedido').click()
        customer.get_by_label('Seu nome', exact=True).fill('Cliente Sacola Salva')
        customer.get_by_label('WhatsApp com DDD').fill('11988887777')
        with customer.expect_response(lambda r: r.url.endswith('/shopping') and r.request.post_data_json.get('recovery_consent') is True):
            customer.get_by_label('Quero um lembrete no WhatsApp', exact=False).check()
        customer.get_by_role('button', name='Fechar', exact=True).click()
        with sqlite3.connect(tmp_path / 'browser.sqlite3') as conn:
            stamp = (datetime.now(timezone.utc) - timedelta(minutes=31)).isoformat(timespec='seconds')
            conn.execute('UPDATE shopping_sessions SET updated_at=? WHERE phone=?', (stamp, '11988887777'))
        page.get_by_role('button', name='Marketing', exact=True).click()
        expect(page.locator('.recovery-card')).to_contain_text('Cliente Sacola Salva')
        page.screenshot(path=str(artifacts / 'marketing-recuperacao-desktop.png'), full_page=True)
        page.get_by_role('button', name='Revisar lembrete', exact=False).click()
        href = page.get_by_role('link', name='Abrir no WhatsApp', exact=False).get_attribute('href')
        message = parse_qs(urlparse(href).query)['text'][0]
        recovery_url = next(part for part in message.split() if '?recuperar=' in part)
        page.get_by_role('button', name='Fechar', exact=True).click()
        recovered = mobile.new_page()
        recovered.on('pageerror', lambda error: errors.append(str(error)))
        recovered.goto(recovery_url)
        recovered.get_by_role('button', name='Continuar com a sacola salva', exact=True).click()
        expect(recovered.locator('.cart-line')).to_contain_text('Burger da casa')
        recovered.get_by_role('button', name='Continuar pedido').click()
        recovered.get_by_label('Seu nome', exact=True).fill('Cliente Sacola Salva')
        recovered.get_by_label('WhatsApp com DDD').fill('11988887777')
        recovered.get_by_label('Endereço completo').fill('Rua de Teste, 15, Centro')
        recovered.get_by_role('button', name='Confirmar pedido').click()
        recovered.wait_for_url('**/pedido/**')
        page.get_by_role('button', name='Marketing', exact=True).click()
        expect(page.locator('.recovery-card')).to_have_count(0)
        for width in (390, 768, 1440):
            page.set_viewport_size({'width': width, 'height': 1000})
            for section in ('Marketing', 'Insumos e fichas'):
                page.get_by_role('button', name=section, exact=True).click()
                expect(page.locator('.growth-hero')).to_be_visible()
                assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), (width, section)
                page.screenshot(path=str(artifacts / (('marketing' if section == 'Marketing' else 'insumos') + '-' + str(width) + '.png')), full_page=True)
        customer.goto(tracking)
        expect(customer.get_by_role('button', name='Pedir de novo', exact=True)).to_be_visible()
        assert not errors, errors
        browser.close()
