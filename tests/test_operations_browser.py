import os
from pathlib import Path

import pytest
from playwright.sync_api import sync_playwright,expect

from tests.test_browser import live


@pytest.mark.skipif(os.getenv('SKIP_BROWSER')=='1',reason='Chromium não instalado')
def test_pos_cash_dining_promotions_purchasing_and_separate_reports(live,tmp_path):
    artifacts=Path('artifacts');artifacts.mkdir(exist_ok=True)
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=os.getenv('PLAYWRIGHT_CHROMIUM_EXECUTABLE') or None)
        page=browser.new_page(viewport={'width':1440,'height':1000});errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto(live+'/entrar')
        page.get_by_label('E-mail',exact=True).fill('demo@example.com');page.get_by_label('Senha',exact=True).fill('senha-de-teste-segura')
        page.get_by_role('button',name='Entrar no painel').click();page.wait_for_url('**/painel')
        page.get_by_role('button',name='Caixa por turno',exact=True).click()
        page.get_by_role('button',name='Abrir turno',exact=True).click()
        page.get_by_label('Fundo de troco',exact=True).fill('100.00')
        page.locator('#cash-form').get_by_role('button',name='Abrir turno',exact=True).click()
        expect(page.locator('#modal')).not_to_be_visible()
        expect(page.get_by_text('Dinheiro esperado',exact=True)).to_be_visible()
        page.get_by_role('button',name='PDV / Balcão',exact=True).click()
        page.locator('#pos-search').fill('Burger')
        page.locator('.pos-product').filter(has_text='Burger da casa').click()
        page.get_by_label('Bacon crocante').check()
        page.get_by_role('button',name='Adicionar ao pedido',exact=True).click()
        expect(page.locator('#pos-total')).to_contain_text('34,00')
        page.screenshot(path=str(artifacts/'pdv-desktop.png'),full_page=True)
        page.get_by_role('button',name='Finalizar pedido',exact=False).click()
        page.get_by_label('Nome do cliente',exact=True).fill('Cliente do Balcão')
        page.get_by_role('button',name='Criar pedido',exact=True).click()
        expect(page.locator('#modal')).not_to_be_visible()
        page.get_by_role('button',name='Caixa por turno',exact=True).click()
        pending=page.locator('tr').filter(has_text='Cliente do Balcão')
        pending.get_by_role('button',name='Receber',exact=True).click()
        page.get_by_label('Valor recebido',exact=True).fill('10.00')
        page.get_by_role('button',name='Registrar recebimento',exact=True).click()
        expect(page.locator('#modal')).not_to_be_visible()
        expect(page.locator('tr').filter(has_text='Cliente do Balcão').filter(has=page.get_by_role('button',name='Receber',exact=True))).to_contain_text('24,00')
        page.screenshot(path=str(artifacts/'caixa-desktop.png'),full_page=True)
        page.get_by_role('button',name='Mesas e comandas',exact=True).click()
        page.get_by_role('button',name='Cadastrar mesa',exact=True).click()
        page.get_by_label('Nome da mesa ou comanda').fill('Mesa 01')
        page.get_by_role('button',name='Cadastrar',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
        page.locator('.dining-card').click();page.get_by_label('Identificação da conta').fill('Família do almoço')
        page.get_by_role('button',name='Abrir conta',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
        expect(page.locator('.dining-card')).to_contain_text('Ocupada')
        page.screenshot(path=str(artifacts/'salao-desktop.png'),full_page=True)
        page.locator('.dining-card').click();page.get_by_role('button',name='Adicionar pedido',exact=True).click()
        page.locator('#pos-search').fill('Suco');page.locator('.pos-product').click()
        page.get_by_role('button',name='Adicionar ao pedido',exact=True).click()
        page.get_by_role('button',name='Finalizar pedido',exact=False).click()
        page.get_by_role('button',name='Criar pedido',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
        page.get_by_role('button',name='Voltar ao salão',exact=False).click()
        expect(page.locator('.dining-card')).to_contain_text('9,90')
        page.get_by_role('button',name='Promoções e horários',exact=True).click()
        page.get_by_role('button',name='Nova regra',exact=True).click()
        page.get_by_label('Nome da regra').fill('Especial da semana')
        page.get_by_label('Produto',exact=True).select_option(label='Burger da casa')
        page.get_by_label('Preço promocional').fill('19.90')
        page.get_by_role('button',name='Salvar regra',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
        expect(page.locator('#dashboard-content')).to_contain_text('Especial da semana')
        page.screenshot(path=str(artifacts/'promocoes-desktop.png'),full_page=True)
        page.get_by_role('button',name='Contas e fornecedores',exact=True).click()
        page.get_by_role('button',name='Nova conta',exact=True).click()
        page.get_by_label('Descrição',exact=True).fill('Compra de insumos')
        page.get_by_label('Valor da conta',exact=True).fill('250.00')
        page.get_by_label('Vencimento',exact=True).fill('2026-11-10')
        page.get_by_role('button',name='Cadastrar conta',exact=True).click();expect(page.locator('#modal')).not_to_be_visible()
        expect(page.locator('#dashboard-content')).to_contain_text('Compra de insumos')
        page.get_by_role('button',name='Gerar relatório',exact=True).click()
        page.screenshot(path=str(artifacts/'relatorios-desktop.png'),full_page=True)
        for fmt,magic in [('pdf',b'%PDF'),('xlsx',b'PK')]:
            page.get_by_label('Formato',exact=True).select_option(fmt)
            with page.expect_download() as download:
                page.locator('#report-form').get_by_role('button',name='Gerar relatório',exact=True).click()
            file=tmp_path/download.value.suggested_filename;download.value.save_as(file)
            assert file.read_bytes().startswith(magic)
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(artifacts/'relatorios-mobile.png'),full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        assert errors==[]
        browser.close()
